// Generates src/theme/tokens.ts from the Faroz source of truth (assets/brand/faroz/tokens.css),
// so the app never hand-writes colours. Gradients and shadows become their first colour, because
// React Native has no CSS gradients or box-shadow strings.
//   node scripts/gen-tokens.mjs           write the file
//   node scripts/gen-tokens.mjs --check   fail if the file is out of date (used by typecheck)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../../assets/brand/faroz/tokens.css');
const target = resolve(here, '../src/theme/tokens.ts');
const css = readFileSync(source, 'utf8');

function block(selector) {
  const start = css.indexOf(selector);
  if (start === -1) throw new Error(`${selector} not found in tokens.css`);
  const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('}', start));
  const out = {};
  for (const line of body.split('\n')) {
    const m = /^\s*--([a-z0-9-]+):\s*(.+?);\s*$/.exec(line);
    if (!m) continue;
    const name = m[1].replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
    let value = m[2];
    if (/^(linear-gradient|0 0)/.test(value)) {
      const color = /(#[0-9A-Fa-f]{3,8}|rgba?\([^)]+\))/.exec(value);
      value = color ? color[1] : 'transparent';
    }
    if (value === 'none') value = 'transparent';
    out[name] = value;
  }
  return out;
}

const dark = block(':root, [data-theme="dark"]');
const light = block('[data-theme="light"]');
const text = `// Generated by scripts/gen-tokens.mjs from assets/brand/faroz/tokens.css. Do not edit by hand.
export const darkTokens = ${JSON.stringify(dark, null, 2)} as const;

export const lightTokens = ${JSON.stringify(light, null, 2)} as const;

export type Tokens = { [K in keyof typeof darkTokens]: string };
`;

if (process.argv.includes('--check')) {
  // Git may check the file out with CRLF line endings on Windows: compare without them.
  if (!existsSync(target) || readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== text) {
    console.error('src/theme/tokens.ts is out of date: run pnpm --filter @nuvora/mobile tokens');
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
  console.log(`Wrote ${target}`);
}
